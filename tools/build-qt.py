#!/usr/bin/env python3
"""Generate language-neutral Qt styles and palette roles from Lattice tokens."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent


def resolve_tokens(tokens: dict, theme: str) -> dict[str, str]:
    raw = {t['name']: t['value'] for family in ('color', 'spacing', 'radius')
           for t in tokens[family]['tokens']}
    resolved: dict[str, str] = {}

    def resolve(name: str, trail: tuple[str, ...] = ()) -> str:
        if name in trail:
            raise ValueError(f"Cyclic token alias: {' -> '.join((*trail, name))}")
        value = raw[name]
        if isinstance(value, dict):
            value = value[theme]
        if value.startswith('{') and value.endswith('}'):
            value = resolve(value[1:-1], (*trail, name))
        resolved[name] = value
        return value

    for name in raw:
        resolve(name)
    return resolved


def qt_color(value: str) -> str:
    # CSS alpha is 0..1; Qt uses 0..255 (or percentages).
    match = re.fullmatch(r'rgba\((\d+),(\d+),(\d+),([\d.]+)\)', value)
    if match:
        r, g, b, alpha = match.groups()
        return f'rgba({r}, {g}, {b}, {round(float(alpha) * 255)})'
    return value


def palette(t: dict[str, str]) -> dict:
    roles = {
        'Window': 'bg', 'WindowText': 'ink', 'Base': 'surface',
        'AlternateBase': 'surface-sunken', 'Text': 'ink',
        'Button': 'surface', 'ButtonText': 'ink', 'BrightText': 'on-accent',
        'Highlight': 'accent', 'HighlightedText': 'on-accent',
        'ToolTipBase': 'surface', 'ToolTipText': 'ink', 'Link': 'accent',
        'LinkVisited': 'accent-ink', 'PlaceholderText': 'ink-subtle',
        'Light': 'surface', 'Midlight': 'surface-sunken', 'Mid': 'line',
        'Dark': 'line', 'Shadow': 'line', 'Accent': 'accent',
    }
    active = {role: t[token] for role, token in roles.items()}
    disabled = dict(active)
    for role in ('WindowText', 'Text', 'ButtonText', 'PlaceholderText'):
        disabled[role] = t['ink-subtle']
    disabled.update(Highlight=t['surface-sunken'], HighlightedText=t['ink-muted'])
    return {'Active': active, 'Inactive': active.copy(), 'Disabled': disabled}


def stylesheet(tokens: dict, theme: str) -> str:
    t = {key: qt_color(value) for key, value in resolve_tokens(tokens, theme).items()}
    # Qt does not perform CSS-style fallback across the web family list.
    # Its terminal generic maps through the platform font database.
    mono = tokens['type']['families']['mono'].split(',')[-1].strip().strip("\"'")
    styles = {s['name']: s for g in tokens['type']['groups'] for s in g['styles']}
    out = [f'/* Generated by tools/build-qt.py from project/tokens.json. Theme: {theme}. Do not edit. */',
           '/* Use Fusion + matching lattice-palette.json for native indicators and unstyled controls. */']

    def rule(selectors: str, **props: str) -> None:
        out.append(selectors + ' {\n' + '\n'.join(
            f'  {key.replace("_", "-")}: {value};' for key, value in props.items()) + '\n}')

    def named(widget: str, component: str) -> str:
        return f'{widget}[lattice="{component}"]'

    rule('QWidget', color=t['ink'], font_size=styles['ui']['fontSize'],
         selection_background_color=t['accent'], selection_color=t['on-accent'])
    rule('QMainWindow, QDialog, QWidget#lattice-root', background=t['bg'])
    rule('QLabel', background='transparent')
    rule('QToolTip', background=t['surface'], color=t['ink'], border=f"1px solid {t['line']}", padding=t['space-2'])
    for component, radius in [('card', 'radius-xl'), ('header', 'radius-md'), ('sidebar', 'radius-md')]:
        rule(named('QFrame', component), background=t['surface'],
             border=f"1px solid {t['line']}", border_radius=t[radius])
    for style in styles.values():
        props = dict(font_size=style['fontSize'], font_weight=str(style['fontWeight']))
        if style['name'] in ('code', 'code-sm'):
            # Qt has no CSS system-ui generic. Keep the platform UI font otherwise.
            props['font_family'] = mono
        rule(named('QLabel', style['name']), **props)
    for component, color in [('section-label', 'ink-subtle'), ('label', 'ink-muted'),
                             ('hint', 'ink-subtle'), ('muted', 'ink-muted')]:
        rule(named('QLabel', component), color=t[color])
    rule(named('QLabel', 'hint'), font_size=styles['caption']['fontSize'])
    rule('QLabel[lattice="hint"][status="bad"]', color=t['bad-ink'])
    for widget in ('QPushButton', 'QToolButton'):
        rule(widget, background=t['surface'], color=t['ink'], border=f"1px solid {t['line']}",
             border_radius=t['radius-lg'], padding=f"{t['space-3']} {t['space-6']}")
        rule(widget + ':hover', background=t['surface-sunken'], border_color=t['ink-subtle'])
        rule(widget + ':pressed, ' + widget + ':checked', background=t['accent-soft'], color=t['accent-ink'])
        for variant in ('primary', 'ghost', 'danger'):
            sel = f'{widget}[variant="{variant}"]'
            bg, fg = {'primary': ('accent', 'on-accent'), 'ghost': ('surface', 'ink-muted'),
                      'danger': ('bad-soft', 'bad-ink')}[variant]
            rule(sel, background='transparent' if variant == 'ghost' else t[bg],
                 color=t[fg], border_color='transparent' if variant == 'ghost' else t['bad' if variant == 'danger' else bg])
            rule(sel + ':hover, ' + sel + ':pressed, ' + sel + ':checked',
                 background=t['accent-strong' if variant == 'primary' else 'surface-sunken' if variant == 'ghost' else 'bad-soft'])
        # Repeat variant specificity so disabled/focus always override variants.
        selectors = [widget] + [f'{widget}[variant="{v}"]' for v in ('primary', 'ghost', 'danger')]
        rule(', '.join(s + ':focus' for s in selectors), border_color=t['focus'])
        rule(', '.join(s + ':disabled' for s in selectors), background=t['surface-sunken'],
             color=t['ink-subtle'], border_color=t['line'])
    fields = ['QLineEdit', 'QTextEdit', 'QPlainTextEdit', 'QComboBox', 'QSpinBox', 'QDoubleSpinBox', 'QDateEdit', 'QTimeEdit', 'QDateTimeEdit']
    rule(', '.join(fields), background=t['surface'], color=t['ink'],
         border=f"1px solid {t['line']}", border_radius=t['radius-lg'], padding=t['space-3'])
    rule(', '.join(f + ':focus' for f in fields), border_color=t['focus'])
    rule(', '.join(f + ':disabled' for f in fields), background=t['surface-sunken'], color=t['ink-subtle'])
    rule('QComboBox QLineEdit', border='none', padding='0px', background='transparent')
    rule('QPlainTextEdit[lattice="code"], QTextEdit[lattice="code"]',
         background=t['surface-sunken'], font_family=mono, font_size=styles['code']['fontSize'])
    # Retain native arrows, checkmarks, partial checks and radio dots. Palette colors them.
    rule('QCheckBox, QRadioButton', spacing=t['space-4'], background='transparent')
    rule('QCheckBox:disabled, QRadioButton:disabled', color=t['ink-subtle'])
    rule('QTabWidget::pane', background=t['surface'], border=f"1px solid {t['line']}")
    rule('QTabBar::tab', background='transparent', color=t['ink-muted'],
         border_bottom='2px solid transparent', padding=f"{t['space-4']} {t['space-7']}")
    rule('QTabBar::tab:selected', color=t['ink'], border_bottom_color=t['accent'])
    rule('QTabBar::tab:hover:!selected', background=t['surface-sunken'])
    rule('QTabBar::tab:disabled', color=t['ink-subtle'])
    for component in ('banner', 'badge', 'pill'):
        sel = named('QLabel', component)
        rule(sel, background=t['surface-sunken'], color=t['ink-muted'],
             border_radius=t['radius-lg' if component == 'banner' else 'radius-sm'],
             padding=f"{t['space-3']} {t['space-5']}")
        for status, token in [('ok', 'ok'), ('warn', 'warn'), ('bad', 'bad'), ('info', 'accent')]:
            props = dict(background=t[token + '-soft'], color=t[token + '-ink'])
            if component == 'banner':
                props['border_left'] = f"3px solid {t[token]}"
            rule(sel + f'[status="{status}"]', **props)
    rule('QAbstractItemView', background=t['surface'], alternate_background_color=t['surface-sunken'],
         color=t['ink-muted'], border=f"1px solid {t['line']}",
         selection_background_color=t['accent'], selection_color=t['on-accent'])
    rule('QAbstractItemView::item', padding=t['space-2'])
    rule('QAbstractItemView::item:hover:!selected', background=t['surface-sunken'])
    rule('QAbstractItemView::item:selected', background=t['accent'], color=t['on-accent'])
    rule('QHeaderView::section, QTableCornerButton::section', background=t['surface-sunken'], color=t['ink-muted'],
         border=f"1px solid {t['line']}", padding=t['space-2'])
    rule('QListWidget[lattice="steps"]::item:selected', background=t['accent-soft'], color=t['accent-ink'], border_left=f"3px solid {t['accent']}")
    rule('QGroupBox', border=f"1px solid {t['line']}", border_radius=t['radius-md'], margin_top=t['space-6'], padding=t['space-4'])
    rule('QGroupBox::title', subcontrol_origin='margin', color=t['ink-muted'], padding=f"0px {t['space-2']}")
    rule('QProgressBar', background=t['surface-sunken'], color=t['ink'], border=f"1px solid {t['line']}", border_radius=t['radius-sm'], text_align='center')
    rule('QProgressBar::chunk', background=t['accent'])
    rule('QMenu, QMenuBar, QStatusBar, QToolBar', background=t['surface'], color=t['ink'])
    rule('QMenu::item:selected, QMenuBar::item:selected', background=t['accent'], color=t['on-accent'])
    for orientation, dimension, minimum in [('vertical', 'width', 'min-height'), ('horizontal', 'height', 'min-width')]:
        sel = f'QScrollBar:{orientation}'
        rule(sel, background=t['bg'], **{dimension: t['space-4']})
        rule(f'QScrollBar::handle:{orientation}', background=t['line'], border_radius=t['radius-md'], **{minimum: t['space-9']})
        rule(f'QScrollBar::handle:{orientation}:hover', background=t['ink-subtle'])
        rule(f'QScrollBar::add-line:{orientation}, QScrollBar::sub-line:{orientation}', **{'height' if orientation == 'vertical' else 'width': '0px'})
        rule(f'QScrollBar::add-page:{orientation}, QScrollBar::sub-page:{orientation}', background='transparent')
    return '\n\n'.join(out) + '\n'


def artifacts(tokens: dict) -> dict[str, str]:
    result = {}
    palettes = {}
    for theme in (theme['id'] for theme in tokens['color']['themes']):
        # Light is the default, matching tokens.css.
        filename = 'lattice.qss' if theme == 'light' else f'lattice-{theme}.qss'
        result[filename] = stylesheet(tokens, theme)
        palettes[theme] = palette(resolve_tokens(tokens, theme))
    result['lattice-palette.json'] = json.dumps(palettes, indent=2) + '\n'
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated Qt artifacts are stale; write nothing')
    args = parser.parse_args()
    tokens = json.loads((ROOT / 'project/tokens.json').read_text(encoding='utf-8'))
    stale = []
    for filename, content in artifacts(tokens).items():
        path = ROOT / 'dist' / filename
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(filename)
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_text(content, encoding='utf-8')
            print(f'wrote dist/{filename}')
    if stale:
        parser.exit(1, 'Stale Qt artifacts: ' + ', '.join(stale) + '. Run python3 tools/build-qt.py\n')


if __name__ == '__main__':
    main()
